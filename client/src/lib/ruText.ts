const getV103Text = (text: string): string | undefined => {
  if (V103_TEXTS[text]) return V103_TEXTS[text];
  for (const { pattern, template } of V103_PATTERNS) {
    const match = text.match(pattern);
    if (match) return template.replace(/\$(\d)/g, (_, index) => match[Number(index)] ?? '');
  }
  return undefined;
};

export const getRussianTextFallback = (text: string): string | undefined => {
  if (V104_RU[text]) return V104_RU[text];
  const v103 = getV103Text(text);
  if (v103) return v103;
  const exact = RU_TEXT_FALLBACKS[text];
  if (exact) return exact;

  for (const { pattern, replace } of RU_TEXT_PATTERNS) {
    const match = text.match(pattern);
    if (match) {
      return replace(...match.slice(1));
    }
  }

  return undefined;
};
